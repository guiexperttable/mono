#!/usr/bin/env node
/**
 * Copies the shared Angular wrapper source into one build harness and generates the component stylesheet.
 *
 *   node scripts/sync-angular-src.mjs ng22        (normally called by `pnpm --filter angular-build-ng22 build`)
 *   node scripts/sync-angular-src.mjs all
 *
 * Source of truth:   packages/angular-table/src            (edit here – never in angular-builds/<ng>/lib/src)
 * Stylesheet:        packages/table/css/table*.css          -> lib/src/lib/table.component.css (generated)
 * Version overrides: angular-builds/<ng>/overrides/**       (optional; copied over the shared source)
 *
 * Version marker (since 1.1.100) – code for newer Angular majors only, kept in the shared source:
 *   - a file whose FIRST line is `// @since-angular 22` is copied only for target majors >= 22;
 *   - a line ending with `// @since-angular 22` (e.g. an export in public-api.ts) is removed for majors < 22.
 *   The major is read from the target name (ng22 -> 22), so a new harness ng23 gets everything marked 22 without
 *   further work.
 *   Limits: mark whole statements that fit on one line (a marker on one line of a multi-line statement leaves the
 *   rest behind); never end a line inside a string or template literal with a marker. Files in overrides/ are copied
 *   unfiltered (they belong to one major anyway).
 */
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, realpathSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** `// @since-angular 22` (first line of a file or end of a line) → 22 */
const SINCE_RE = /\/\/\s*@since-angular\s+(\d+)\s*$/;

/** The Angular major of a build target name: "ng22" → 22. */
export function majorOfTarget(target) {
  const m = /^ng(\d+)$/.exec(target);
  if (!m) {
    throw new Error(`Not a build target name: ${target} (expected ng<major>)`);
  }
  return Number(m[1]);
}

/** The minimal major of a marked line or `undefined` (no marker). */
export function sinceOf(line) {
  const m = SINCE_RE.exec(line);
  return m ? Number(m[1]) : undefined;
}

/**
 * The text of a source file for one Angular major: `null` = the file is left out (marked for a newer major),
 * otherwise the text without the lines marked for newer majors. Unmarked text is returned unchanged.
 */
export function filterSourceForMajor(text, major) {
  const lines = text.split("\n");
  const fileSince = sinceOf(lines[0]);
  if (fileSince !== undefined && lines[0].trim().startsWith("//") && lines[0].trim().replace(SINCE_RE, "").trim() === "") {
    if (major < fileSince) {
      return null;
    }
    return text;
  }
  const kept = lines.filter(line => {
    const since = sinceOf(line);
    return since === undefined || major >= since;
  });
  return kept.length === lines.length ? text : kept.join("\n");
}

/** Recursive copy (plain fs calls – fs.cpSync fails on some mounted/network file systems). */
function copyDir(from, to, major) {
  mkdirSync(to, { recursive: true });
  for (const name of readdirSync(from)) {
    const a = join(from, name);
    const b = join(to, name);
    if (statSync(a).isDirectory()) {
      copyDir(a, b, major);
    } else if (major !== undefined && name.endsWith(".ts")) {
      const text = filterSourceForMajor(readFileSync(a, "utf8"), major);
      if (text !== null) {
        writeFileSync(b, text);
      }
    } else {
      copyFileSync(a, b);
    }
  }
}

const defaultRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/**
 * Syncs one build harness. `dirs` defaults to the repo (tests pass temporary directories).
 *
 * @param {string} target  e.g. "ng22"
 * @param {{ sharedDir?: string, cssDir?: string, buildsDir?: string, log?: boolean }} [dirs]
 */
export function syncTarget(target, dirs = {}) {
  const sharedDir = dirs.sharedDir ?? join(defaultRoot, "packages/angular-table");
  const cssDir = dirs.cssDir ?? join(defaultRoot, "packages/table/css");
  const buildsDir = dirs.buildsDir ?? join(defaultRoot, "angular-builds");
  const buildDir = join(buildsDir, target);
  const libDir = join(buildDir, "lib");
  if (!/^ng\d+$/.test(target) || !existsSync(join(buildDir, "package.json"))) {
    throw new Error(`Unknown build target: ${target}`);
  }
  const major = majorOfTarget(target);
  const cssFiles = readdirSync(cssDir).filter(f => /^table.*\.css$/.test(f)).sort(); // same as `cat css/table*.css`
  const css = "/* GENERATED by scripts/sync-angular-src.mjs from packages/table/css/table*.css – do not edit. */\n"
    + cssFiles.map(f => readFileSync(join(cssDir, f), "utf8")).join("\n");

  const srcOut = join(libDir, "src");
  rmSync(srcOut, { recursive: true, force: true });
  copyDir(join(sharedDir, "src"), srcOut, major);

  const overrides = join(buildDir, "overrides");
  if (existsSync(overrides)) {
    copyDir(overrides, srcOut, undefined);
  }

  mkdirSync(join(srcOut, "lib"), { recursive: true });
  writeFileSync(join(srcOut, "lib/table.component.css"), css);

  for (const f of ["README.md", "LICENSE"]) {
    copyFileSync(join(sharedDir, f), join(libDir, f));
  }
  if (dirs.log !== false) {
    console.log(`synced packages/angular-table -> angular-builds/${target}/lib (Angular ${major}; css: ${cssFiles.join(", ")})`);
  }
}

/** `true` when this file is the script node was started with (also through a symlink or another drive-letter case). */
function isCli() {
  if (!process.argv[1]) {
    return false;
  }
  try {
    return realpathSync(resolve(process.argv[1])) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

// CLI (not when imported by a test)
if (isCli()) {
  const arg = process.argv[2];
  if (!arg) {
    console.error("Usage: node scripts/sync-angular-src.mjs <ng14..ng22|all>");
    process.exit(1);
  }
  const buildsDir = join(defaultRoot, "angular-builds");
  const targets = arg === "all"
    ? readdirSync(buildsDir).filter(d => /^ng\d+$/.test(d)).sort()
    : [arg];
  try {
    targets.forEach(t => syncTarget(t));
  } catch (e) {
    console.error(e instanceof Error ? e.message : e);
    process.exit(1);
  }
}
